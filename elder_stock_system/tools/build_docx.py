def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def para(text, bold=False, color=None, size=None, align=None, italic=False, style=None):
    p = doc.add_paragraph(style=style)
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if color is not None:
        r.font.color.rgb = color
    if size:
        r.font.size = Pt(size)
    if align:
        p.alignment = align
    return p


def bullets(items, style="List Bullet"):
    for t in items:
        p = doc.add_paragraph(style=style)
        if "::" in t:
            h, b = t.split("::", 1)
            r = p.add_run(h); r.bold = True
            p.add_run(b)
        else:
            p.add_run(t)


def table(rows, widths, header=True, fs=9, first_col_bold=False, zebra=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.cell(i, j)
            c.width = Cm(widths[j])
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.line_spacing = 1.15
            r = p.add_run(str(val))
            r.font.size = Pt(fs)
            if header and i == 0:
                r.bold = True; r.font.color.rgb = RGBColor(255, 255, 255); shade(c, "1F3A5F")
            else:
                if first_col_bold and j == 0:
                    r.bold = True
                if zebra and i % 2 == 0:
                    shade(c, "F2F4F7")
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


